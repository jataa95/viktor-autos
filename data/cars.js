export function similarCars(car, n = 3) {
  return cars
    .filter((c) => c.slug !== car.slug)
    .map((c) => ({ c, score: (c.body === car.body ? 2 : 0) + (c.make === car.make ? 1 : 0) - Math.abs(c.price - car.price) / 1e8 }))
    .sort((a, b) => b.score - a.score)
    .slice(0, n)
    .map((x) => x.c);
}
